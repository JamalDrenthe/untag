export function translate(language: Language, key: keyof typeof copy.nl): string {
  return copy[language][key]
}

export function fieldName(language: Language, key: string): string {
  return fields[key]?.[language] ?? key
}

export function groupName(language: Language, key: string): string {
  return groups[key]?.[language] ?? key
}

export function metadataLabel(language: Language, label: string): string {
  if (language === 'nl' && label.startsWith('RIFF ') && label.endsWith(' chunk')) {
    return `${label.slice(5, -6)}-chunk`
  }
  return metadataLabels[label]?.[language] ?? label
}

export function metadataValue(language: Language, value: string): string {
  if (language === 'nl') {
    return value
      .replace(/, front cover\b/g, ', voorzijde')
      .replace(/, back cover\b/g, ', achterzijde')
      .replace(/\brating\b/g, 'waardering')
      .replace(/\bplays\b/g, 'afspeelbeurten')
  }
  return value
}
